def sudo_write(path, content):
    tmp = "/tmp/astgen.tmp"
    with open(tmp, "w") as f:
        f.write(content)
    subprocess.run(["sudo", "-n", "cp", path, path + ".bak-guardian"], capture_output=True)
    r = subprocess.run(["sudo", "-n", "cp", tmp, path], capture_output=True, text=True)
    print("wrote", path, "rc", r.returncode, r.stderr.strip()[:100])

sudo_write("/etc/asterisk/pjsip.conf", PJSIP)
sudo_write("/etc/asterisk/extensions.conf", EXTEN.replace("__SIPUSER__", USER))
sudo_write("/etc/asterisk/confbridge_grd.conf", CONFBRIDGE)
try:
    cb = open("/etc/asterisk/confbridge.conf").read()
except Exception:
    cb = ""
if "confbridge_grd.conf" not in cb:
    sudo_write("/etc/asterisk/confbridge.conf", cb.rstrip() + "\n#include confbridge_grd.conf\n")
    print("confbridge include added")
subprocess.run(["sudo", "-n", "mkdir", "-p", "/var/spool/asterisk/monitor"], capture_output=True)
subprocess.run(["sudo", "-n", "mkdir", "-p", "/var/spool/asterisk/grd-lines"], capture_output=True)
subprocess.run(["sudo", "-n", "chown", "asterisk:asterisk", "/var/spool/asterisk/grd-lines"], capture_output=True)
subprocess.run(["sudo", "-n", "chmod", "2775", "/var/spool/asterisk/grd-lines"], capture_output=True)
r = subprocess.run(["sudo", "-n", "systemctl", "restart", "asterisk"], capture_output=True, text=True)
print("asterisk restart rc", r.returncode)
